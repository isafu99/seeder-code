def dim(ax, p1, p2, txt, vertical=False, fs=6.5, off=0.06):
    ax.annotate('', xy=p1, xytext=p2, arrowprops=dict(arrowstyle='<->', lw=0.6, color=MUT, shrinkA=0, shrinkB=0))
    xm, ym = (p1[0]+p2[0])/2, (p1[1]+p2[1])/2
    if vertical: ax.text(xm+off, ym, txt, rotation=90, va='center', ha='left', fontsize=fs, color=MUT)
    else: ax.text(xm, ym+off, txt, ha='center', va='bottom', fontsize=fs, color=MUT)
def save(fig, name):
    fig.savefig(OUT+name, dpi=220, bbox_inches='tight', facecolor='white'); plt.close(fig)
def rect(ax, x0, y0, w, h, **kw):
    kw.setdefault('fill', False); kw.setdefault('lw', 0.8); kw.setdefault('ec', INK)
    ax.add_patch(Rectangle((x0, y0), w, h, **kw))

